#!/usr/bin/env python3
"""Regenerates docs/CONTENT_REVIEW.md from the seed data.

Run after changing entities.json or sources.json (standard library only):

    python3 scripts/generate_content_review.py
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
DATA_DIR = ROOT / "DivineAtlas" / "Resources" / "SeedData"
OUTPUT = ROOT / "docs" / "CONTENT_REVIEW.md"
TRADITIONS = {"christianity": "Christianity", "judaism": "Judaism", "islam": "Islam", "hinduism": "Hinduism"}


def records(name):
    return json.loads((DATA_DIR / f"{name}.json").read_text())["records"]


def main():
    entities = records("entities")
    source_titles = {s["id"]: s["title"] for s in records("sources")}
    names = {e["id"]: e["name"] for e in entities}

    def citations(item):
        return "; ".join(
            source_titles[c["sourceID"]] + (f", {c['locator']}" if c.get("locator") else "")
            for c in item.get("citations", [])
        )

    def status(entity):
        return "☑" if entity.get("reviewStatus") == "reviewed" else "☐"

    lines = [
        "# Content Review Checklist",
        "",
        "Generated by `scripts/generate_content_review.py` from the seed data. Do not edit by hand.",
        "There is one row per tradition-specific classification. A reviewer checks each claim against",
        "the cited passage in a chosen edition, records that edition in `sources.json`, and sets the",
        "entry's `reviewStatus` to `reviewed` with a `lastReviewedAt` date. ☑ marks reviewed entries.",
        "",
        "| ✓ | Entry | Tradition | Classification | Citations |",
        "| --- | --- | --- | --- | --- |",
    ]
    for entity in entities:
        for c in entity["classifications"]:
            lines.append(
                f"| {status(entity)} | {entity['name']} (`{entity['id']}`) | {TRADITIONS[c['traditionID']]} "
                f"| {c['label']} | {citations(c)} |"
            )

    lines += ["", "## Relationships", "", "| ✓ | From | To | Explanation | Citations |", "| --- | --- | --- | --- | --- |"]
    for entity in entities:
        for r in entity.get("relationships", []):
            lines.append(
                f"| {status(entity)} | {entity['name']} | {names[r['relatedEntityID']]} | {r['explanation']} "
                f"| {citations(r) or '— (editorial)'} |"
            )

    OUTPUT.write_text("\n".join(lines) + "\n")
    print(f"Wrote {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
